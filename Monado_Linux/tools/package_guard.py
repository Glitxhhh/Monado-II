"""Source/package guard (Constitution art. I, SC-012; [XCDE] LINUX-001).

Usage: package_guard.py <candidate-dir> [...] | --git <repo-or-subdirectory>
Tree mode checks a prepared source/package candidate, not a development tree.
Git mode checks every indexed blob from the repository root, including when invoked
inside Monado_Linux. The index is the staging candidate; worktree replacements
must not hide staged data. Neither mode follows symlinks or prints file contents.

These checks supplement a reviewed source allowlist. Arbitrarily renamed opaque
game data has no universal signature; a pass is not a provenance determination.
"""
import os
import re
import stat
import subprocess
import sys

FORBIDDEN_EXT = (
    '.nsp', '.xci', '.nca', '.nsz', '.xcz', '.nso', '.nro', '.bfttf', '.bfotf',
    '.exe', '.dll', '.so', '.dylib', '.o', '.obj', '.a', '.lib', '.pdb', '.pyc',
    '.spv', '.cso', '.dxil', '.bin', '.pack', '.idx', '.sav', '.save', '.journal',
    '.tmb', '.log', '.dmp', '.keys',
)
FORBIDDEN_DIRS = {
    'targets', 'generated', 'extracted', 'romfs', 'exefs', 'game_files', 'local_assets',
    'build', 'cache', 'caches', 'save', 'saves', 'runs', 'accepted', 'crash',
    'play', 'logs', 'screenshots', 'captures', 'keys', '.venv', '.deps',
    'backup', 'backups', 'mods', 'reports',
    '__pycache__', 'node_modules',
}
SKIP_DIRS = {'.git'}  # repository metadata is not part of a source candidate
KEY_NAMES = {'prod.keys', 'title.keys', 'dev.keys', 'title.keys_autogenerated'}
ARTIFACT_NAMES = {'variants_seed.bin', 'variants.bin', 'spirv.pack', 'spirv.idx', 'vk_pipelines.bin'}
STATE_NAMES = {'xcde.ini'}
KEY_RE = re.compile(rb'(master_key|titlekek|key_area_key|aes_kek_generation)[a-z_0-9]*\s*=\s*[0-9a-fA-F]{32}')
LIFTED_RE = re.compile(
    rb'\bvoid\s+f_[0-9a-fA-F]{6,}\s*\(\s*Cpu\s*\*\s*'
    rb'(?:(?:restrict|__restrict|__restrict__|const|volatile)\s+)*c\s*\)')
SAVE_RE = re.compile(r'save_[0-9]+(?:$|[._])')
TEXT_SCAN_MAX = 8 * 1024 * 1024  # larger files require explicit source/provenance review
C_EXT = ('.c', '.h', '.inc', '.cpp', '.cc', '.cxx', '.hpp')


def _path_violation(name):
    low = name.replace('\\', '/').lower()
    parts = low.split('/')
    if low.startswith('/') or '..' in parts:
        return 'unsafe path'
    if parts[-1] in KEY_NAMES:
        return 'key file'
    if any(p in FORBIDDEN_DIRS or SAVE_RE.match(p) for p in parts):
        return 'forbidden directory or runtime-state path'
    if parts[-1] in ARTIFACT_NAMES:
        return 'game-run cache/seed'
    if parts[-1] in STATE_NAMES:
        return 'runtime configuration'
    if low.endswith(FORBIDDEN_EXT) or re.search(r'\.so(?:\.[0-9]+)+$', low):
        return 'forbidden extension'
    return None


def _content_violation(name, data):
    if data[:4] == b'NSO0':
        return 'NSO binary (by magic)'
    if (data.startswith((b'\x7fELF', b'MZ', b'!<arch>\n', b'!<thin>\n')) or
            data[:4] in (b'\xfe\xed\xfa\xce', b'\xce\xfa\xed\xfe',
                         b'\xfe\xed\xfa\xcf', b'\xcf\xfa\xed\xfe',
                         b'\xca\xfe\xba\xbe', b'\xbe\xba\xfe\xca')):
        return 'compiled binary (by magic)'
    if data[:4] in (b'\x03\x02\x23\x07', b'\x07\x23\x02\x03'):
        return 'compiled SPIR-V (by magic)'
    if data[:4] == b'XCVC':  # documented by tools/merge_variants.py
        return 'game-run shader variants (by magic)'
    if KEY_RE.search(data):
        return 'key material in file'
    if name.lower().endswith(C_EXT) and LIFTED_RE.search(data):
        return 'lifted game code'
    return None


def _scan_file(path, name):
    reason = _path_violation(name)
    if reason:
        return [f'{reason}: {name}']
    try:
        before = os.lstat(path)
        if stat.S_ISLNK(before.st_mode):
            return [f'symlink is not a source/package file: {name}']
        if not stat.S_ISREG(before.st_mode):
            return [f'non-regular file: {name}']
        # O_NOFOLLOW also rejects a file changed into a link between lstat/open.
        flags = (os.O_RDONLY | getattr(os, 'O_BINARY', 0) | getattr(os, 'O_NOFOLLOW', 0) |
                 getattr(os, 'O_NONBLOCK', 0))
        fd = os.open(path, flags)
        with os.fdopen(fd, 'rb') as source:
            actual = os.fstat(source.fileno())
            if (not stat.S_ISREG(actual.st_mode) or
                    (before.st_dev, before.st_ino) != (actual.st_dev, actual.st_ino)):
                return [f'file changed during scan: {name}']
            if actual.st_size > TEXT_SCAN_MAX:
                return [f'file exceeds scan limit; explicit review required: {name}']
            data = source.read(TEXT_SCAN_MAX + 1)
        if len(data) > TEXT_SCAN_MAX:
            return [f'file exceeds scan limit; explicit review required: {name}']
    except OSError as exc:
        return [f'cannot read candidate file ({type(exc).__name__}): {name}']
    reason = _content_violation(name, data)
    return [f'{reason}: {name}'] if reason else []


def scan(root):
    root = os.path.abspath(root)
    if os.path.islink(root):
        return ['symlink candidate root is not allowed']
    if not os.path.isdir(root):
        return ['candidate root is missing or not a directory']
    reason = _path_violation(os.path.basename(root))
    if reason:
        return [f'{reason}: {os.path.basename(root)}']
    out = []

    def onerror(exc):
        out.append(f'cannot enumerate candidate directory ({type(exc).__name__})')

    for dirpath, dirs, files in os.walk(root, followlinks=False, onerror=onerror):
        kept = []
        for directory in sorted(dirs):
            path = os.path.join(dirpath, directory)
            name = os.path.relpath(path, root)
            if directory == '.git':
                continue
            if os.path.islink(path):
                out.append(f'symlink directory is not allowed: {name}')
                continue
            reason = _path_violation(name)
            if reason:
                out.append(f'{reason}: {name}')
                continue  # report without reading shared input or runtime data
            kept.append(directory)
        dirs[:] = kept
        for filename in sorted(files):
            if filename == '.git':
                continue  # linked-worktree metadata file
            path = os.path.join(dirpath, filename)
            out.extend(_scan_file(path, os.path.relpath(path, root)))
    return out


def _git(repo, *args):
    return subprocess.run(['git', '-C', os.fspath(repo), *args], check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout


def scan_tracked(repo):
    """Inspect the index's full candidate tree, not unstaged worktree contents."""
    try:
        top = os.fsdecode(_git(repo, 'rev-parse', '--show-toplevel').rstrip(b'\n'))
        records = _git(top, 'ls-files', '--stage', '-z').split(b'\0')
    except (OSError, subprocess.CalledProcessError):
        return ['cannot enumerate Git index; source candidate not verified']
    out = []
    for record in filter(None, records):
        try:
            metadata, raw_name = record.split(b'\t', 1)
            mode, oid, stage = metadata.split()
            name = os.fsdecode(raw_name)
        except ValueError:
            out.append('invalid Git index entry; source candidate not verified')
            continue
        reason = _path_violation(name)
        if reason:
            out.append(f'{reason}: {name}')
            continue
        if stage != b'0':
            out.append(f'unmerged index entry: {name}')
            continue
        if mode == b'120000':
            out.append(f'symlink index entry is not allowed: {name}')
            continue
        if mode not in (b'100644', b'100755'):
            out.append(f'unsupported index mode {os.fsdecode(mode)}: {name}')
            continue
        try:
            object_id = oid.decode('ascii')
            size = int(_git(top, 'cat-file', '-s', object_id))
            if size > TEXT_SCAN_MAX:
                out.append(f'file exceeds scan limit; explicit review required: {name}')
                continue
            data = _git(top, 'cat-file', 'blob', object_id)
            if len(data) != size or len(data) > TEXT_SCAN_MAX:
                out.append(f'invalid indexed blob size: {name}')
                continue
        except (OSError, subprocess.CalledProcessError, UnicodeError, ValueError):
            out.append(f'cannot read indexed blob: {name}')
            continue
        reason = _content_violation(name, data)
        if reason:
            out.append(f'{reason}: {name}')
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if not argv or (argv[0] == '--git' and len(argv) > 2):
        print(__doc__)
        return 1
    if argv[0] == '--git':
        bad = scan_tracked(argv[1] if len(argv) > 1 else '.')
    else:
        bad = [v for root in argv for v in scan(root)]
    for violation in bad:
        print('VIOLATION:', violation)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
